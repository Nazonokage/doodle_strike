#!/usr/bin/env python3
"""Generate packages/sim/lib/src/math/trig_table.g.dart.

The generated file is CHECKED IN and is the source of truth. Do not regenerate
casually: changing any value changes every state hash and breaks replays.
Exact values are forced at quarter turns (multiples of 256 table steps).
"""
import math, pathlib

STEPS = 1024
out = []
for i in range(STEPS):
    if i % 256 == 0:
        v = {0: 0.0, 256: 1.0, 512: 0.0, 768: -1.0}[i]
    else:
        v = math.sin(2.0 * math.pi * i / STEPS)
    out.append(repr(float(v)))

lines = ["// GENERATED by tools/gen_trig_table.py. Checked in on purpose; do not hand-edit.",
         "// 1024-step sine table. Cosine is read from this table at a 256-step offset.",
         "const List<double> kSinTable = <double>["]
for k in range(0, STEPS, 4):
    lines.append("  " + ", ".join(out[k:k+4]) + ",")
lines.append("];")
path = pathlib.Path(__file__).resolve().parents[1] / "packages/sim/lib/src/math/trig_table.g.dart"
path.write_text("\n".join(lines) + "\n")
print("wrote", path)
